// Global translation function
window.currentLang = localStorage.getItem('language') || 'en';

function setLanguage(lang) {
    window.currentLang = lang;
    localStorage.setItem('language', lang);
    applyTranslations();
    
    // Dispatch an event so other scripts can re-render dynamic content if needed
    window.dispatchEvent(new Event('languageChanged'));
}

function applyTranslations() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[key] && translations[key][window.currentLang]) {
            // Update placeholders for inputs, otherwise textContent
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[key][window.currentLang];
            } else {
                el.textContent = translations[key][window.currentLang];
            }
        }
    });

    // Update active state of language toggle buttons if they exist
    const btnEn = document.getElementById('lang-en');
    const btnMr = document.getElementById('lang-mr');
    const activeBg = document.getElementById('lang-active-bg');
    
    if (btnEn && btnMr && activeBg) {
        if (window.currentLang === 'en') {
            activeBg.classList.remove('translate-x-full');
            activeBg.classList.add('translate-x-0');
            btnEn.classList.add('text-on-primary');
            btnEn.classList.remove('text-on-surface-variant');
            btnMr.classList.add('text-on-surface-variant');
            btnMr.classList.remove('text-on-primary');
        } else {
            activeBg.classList.remove('translate-x-0');
            activeBg.classList.add('translate-x-full');
            btnMr.classList.add('text-on-primary');
            btnMr.classList.remove('text-on-surface-variant');
            btnEn.classList.add('text-on-surface-variant');
            btnEn.classList.remove('text-on-primary');
        }
    }
}

// Run translation on load
document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    
    // Bind toggle buttons if present
    const btnEn = document.getElementById('lang-en');
    const btnMr = document.getElementById('lang-mr');
    if(btnEn) btnEn.addEventListener('click', () => setLanguage('en'));
    if(btnMr) btnMr.addEventListener('click', () => setLanguage('mr'));
});
